    ! because it updates rates immediately before calling Integrate.
    ICNTRL(15) = 5
    IF ( PRESENT( ICNTRL_U ) ) THEN
       WHERE ( ICNTRL_U /= 0 ) ICNTRL = ICNTRL_U
    ENDIF

